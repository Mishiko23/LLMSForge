const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
    const browser = await chromium.launch({headless: true, ...(process.env.LLMS_BROWSER ? {executablePath: process.env.LLMS_BROWSER} : {})});
    const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setContent('<html><body style="background:#f2f5f7"><div id="llmsforge-app"></div></body></html>');
    await page.addStyleTag({content: fs.readFileSync(path.join(__dirname, '../assets/components/llmsforge/mgr.css'), 'utf8')});
    await page.evaluate(() => {
        window.LLMSForgeConfig = {url: '/test', csrf: 'test'};
        window.Ext = {onReady: fn => fn()};
        window.MODx = {add: config => config.listeners.afterrender()};
        window.saved = null;
        window.fetch = async (url, options) => {
            const data = Object.fromEntries(options.body);
            let result = {};
            if (data.action === 'contexts') result = {contexts: [{key: 'web', name: 'Основной сайт'}]};
            if (data.action === 'load') result = {settings: {title: 'Магазин мебели', description: 'Мебель для дома и офиса', include_ids: '1', exclude_ids: '', sections: '{}', main_mode: 'auto', main_markdown: '', enabled: '0', documents: '[]'}, resources: [{id: 1, title: 'О компании', published: true}, {id: 2, title: 'Кресло Nordic', published: true}], public_url: 'https://example.com/llms.txt'};
            if (data.action === 'preview') result = {text: '# Магазин мебели\n\n## Материалы для AI\n\n- [Кресло Nordic](https://example.com/llms-txt/nordic)'};
            if (data.action === 'preview_document') result = {text: '# Кресло Nordic\n\nОписание товара'};
            if (data.action === 'save') window.saved = data;
            if (data.action === 'visits') result = {total: 1, success: 1, bots: {GPTBot: 1}, rows: [{time: '2026-10-30T10:00:00Z', bot: 'GPTBot', path: '/llms.txt', method: 'GET', status: 200}]};
            if (data.action === 'diagnostics') result = {checks: {'Маршрут llms.txt': true, 'Запись журнала': false}, url: 'https://example.com/llms.txt'};
            return {ok: true, json: async () => ({success: true, object: result})};
        };
    });
    await page.addScriptTag({content: fs.readFileSync(path.join(__dirname, '../assets/components/llmsforge/mgr.js'), 'utf8')});
    await page.getByText('Настройки контекста «web» загружены.').waitFor();
    await page.locator('#lf-check').click();
    assert.match(await page.locator('#lf-diagnostics').textContent(), /Маршрут llms.txt/);
    await page.locator('#lf-visit-refresh').click();
    assert.match(await page.locator('#lf-visit-rows').textContent(), /GPTBot/);
    assert.match(await page.locator('#lf-visit-summary').textContent(), /Запросов: 1/);
    await page.locator('#lf-select-all').click();
    assert.equal(await page.locator('#lf-include_ids').inputValue(), '1,2');
    await page.locator('#lf-search').fill('Nordic');
    await page.locator('#lf-select-none').click();
    assert.equal(await page.locator('#lf-include_ids').inputValue(), '1');
    await page.locator('#lf-select-invert').click();
    assert.equal(await page.locator('#lf-include_ids').inputValue(), '1,2');
    await page.locator('#lf-clear-all').click();
    assert.equal(await page.locator('#lf-include_ids').inputValue(), '');
    await page.locator('#lf-search').fill('');
    await page.locator('#lf-select-published').click();
    assert.equal(await page.locator('#lf-include_ids').inputValue(), '1,2');
    assert.match(await page.locator('#lf-stats').textContent(), /Выбрано ID/);
    await page.locator('#lf-main_mode').selectOption('manual');
    assert.equal(await page.locator('#lf-auto-area').isVisible(), false);
    await page.locator('#lf-main_markdown').fill('# Магазин мебели\n\n> Мебель для дома и офиса');
    await page.locator('#lf-add-document').click();
    const card = page.locator('.lf-document');
    await card.getByLabel('Название', {exact: true}).fill('Кресло Nordic');
    await card.getByLabel('Адрес Markdown: /llms-txt/…').fill('nordic');
    await card.getByLabel('Полный URL исходной страницы').fill('https://example.com/nordic');
    await card.getByLabel('Markdown для AI').fill('# Кресло Nordic\n\nМатериал: дуб.');
    await card.getByText('Предпросмотр страницы', {exact: true}).click();
    assert.match(await page.locator('#lf-output').textContent(), /Кресло Nordic/);
    await page.locator('#lf-enabled').selectOption('1');
    await page.locator('#lf-save').click();
    const saved = await page.evaluate(() => window.saved);
    assert.equal(saved.enabled, '1');
    assert.equal(JSON.parse(saved.documents)[0].slug, 'nordic');
    await page.locator('#lf-preview').click();
    assert.match(await page.locator('#lf-stats').textContent(), /байт/);
    assert.equal(await page.locator('#lf-download').isEnabled(), true);
    await page.locator('#lf-main_mode').selectOption('auto');
    await page.locator('#lf-search').fill('Nordic');
    await page.locator('#lf-generate-documents').click();
    assert.equal(await page.locator('.lf-document').count(), 2);
    assert.equal(await page.locator('.lf-document').last().getAttribute('open'), null);
    await page.locator('.lf-document').last().locator('summary').click();
    await page.waitForFunction(() => [...document.querySelectorAll('.lf-document:last-child select')].some(select => select.value === '2'));
    assert.equal(await page.locator('.lf-document').last().getByLabel('Ресурс: страница, товар, категория или статья').inputValue(), '2');
    await page.locator('#lf-generate-documents').click();
    assert.equal(await page.locator('.lf-document').count(), 2);
    fs.mkdirSync(path.join(__dirname, '../docs'), {recursive: true});
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path: path.join(__dirname, '../docs/admin-preview.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const large = await browser.newPage({viewport: {width: 1440, height: 900}});
    await large.setContent('<html><body><div id="llmsforge-app"></div></body></html>');
    await large.evaluate(() => {
        window.LLMSForgeConfig = {url: '/test', csrf: 'test'};
        window.Ext = {onReady: fn => fn()};
        window.MODx = {add: config => config.listeners.afterrender()};
        window.fetch = async (_url, options) => {
            const action = new URLSearchParams(options.body).get('action');
            const data = action === 'contexts' ? {contexts: [{key: 'web', name: 'Site'}]} : {
                settings: {title: 'Site', description: '', include_ids: '', exclude_ids: '', sections: '{}', main_mode: 'auto', main_markdown: '', enabled: '0', documents: '[]'},
                resources: Array.from({length: 5000}, (_, i) => ({id: i + 1, title: 'Page ' + (i + 1), published: true})),
                public_url: 'https://example.com/llms.txt'
            };
            return {ok: true, json: async () => ({success: true, object: data})};
        };
    });
    await large.addScriptTag({content: fs.readFileSync(path.join(__dirname, '../assets/components/llmsforge/mgr.js'), 'utf8')});
    await large.getByText('Настройки контекста «web» загружены.').waitFor();
    assert.equal(await large.locator('#lf-rows tr').count(), 25);
    assert.match(await large.locator('#lf-page-info').textContent(), /1–25 из 5000/);
    await large.locator('#lf-page-next').click();
    assert.match(await large.locator('#lf-page-info').textContent(), /26–50 из 5000/);
    await large.locator('#lf-search').fill('4999');
    assert.equal(await large.locator('#lf-rows tr').count(), 1);
    assert.match(await large.locator('#lf-page-info').textContent(), /1–1 из 1/);
    await large.locator('#lf-add-document').click();
    const largeCard = large.locator('.lf-document').last();
    await largeCard.getByLabel('Источник содержимого').selectOption('resource');
    await largeCard.getByLabel('Поиск ресурса по названию или ID').fill('4999');
    const picker = largeCard.getByLabel('Ресурс: страница, товар, категория или статья');
    assert.equal(await picker.locator('option').count(), 2);
    await picker.selectOption('4999');
    assert.equal(await largeCard.getByLabel('ID ресурса (можно ввести вручную)').inputValue(), '4999');
    assert.equal(await largeCard.getByLabel('Название', {exact: true}).inputValue(), 'Page 4999');
    assert.equal(await largeCard.getByLabel('Адрес Markdown: /llms-txt/…').inputValue(), 'resource-4999');
    await large.close();
    assert.deepEqual(errors, []);
    await browser.close();
    console.log('Interface checks passed (mock MODX API): edit, cards, preview, save, mobile layout.');
})().catch(error => { console.error(error); process.exit(1); });
